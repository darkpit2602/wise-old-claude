/**
 * Generates TypeScript schema modules from the shared contract schemas. Embedding each schema as a module
 * (rather than reading a JSON file at runtime) means both the tsc build and the single-file bundle carry it,
 * so an installed plugin never depends on files outside its own code. contract/ stays the single source of
 * truth; the generated modules are gitignored and rebuilt before build, test, typecheck and bundle.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const packageRoot = join(import.meta.dirname, "..");
const contractDir = join(packageRoot, "..", "..", "contract");

const modules = [
  { schema: "player-snapshot.schema.json", target: ["snapshot", "playerSnapshot.schema.ts"], exportName: "playerSnapshotSchema" },
  { schema: "nearby-objects.schema.json", target: ["objects", "nearbyObjects.schema.ts"], exportName: "nearbyObjectsSchema" },
  { schema: "nearby-npcs.schema.json", target: ["npcs", "nearbyNpcs.schema.ts"], exportName: "nearbyNpcsSchema" },
  { schema: "ground-items.schema.json", target: ["groundItems", "groundItems.schema.ts"], exportName: "groundItemsSchema" },
  { schema: "game-context.schema.json", target: ["context", "gameContext.schema.ts"], exportName: "gameContextSchema" },
  { schema: "quest-progress.schema.json", target: ["quests", "questProgress.schema.ts"], exportName: "questProgressSchema" },
];

for (const { schema, target, exportName } of modules) {
  const parsed = JSON.parse(readFileSync(join(contractDir, schema), "utf8"));
  const module = [
    `/** Generated by scripts/sync-contract.mjs from contract/${schema}. Do not edit. */`,
    `export const ${exportName}: Record<string, unknown> = ${JSON.stringify(parsed, null, 2)};`,
    "",
  ].join("\n");
  writeFileSync(join(packageRoot, "src", ...target), module);
}
